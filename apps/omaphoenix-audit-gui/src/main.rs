//! OmaPhoenix Audit desktop app (Slint), a front end of `phx-audit`.

#[allow(
    unsafe_code,
    clippy::all,
    clippy::pedantic,
    clippy::unwrap_used,
    clippy::panic,
    missing_docs,
    unused_qualifications,
    reason = "generated by slint-build"
)]
mod ui {
    slint::include_modules!();
}

mod actions;
mod assistant;
mod scan;
mod state;
mod terminal;
mod theme;

use std::env;
use std::fs;
use std::process::Command;

use slint::ComponentHandle;
use ui::{App, Theme};

fn main() -> Result<(), slint::PlatformError> {
    let app = App::new()?;
    slint::set_xdg_app_id("omaphoenix-audit-gui")?;
    if let Some(tokens) = theme::theme_file().and_then(|p| theme::read_tokens(&p)) {
        theme::apply_theme(&app, &tokens);
    }
    let font = Command::new("omarchy-font-current")
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_default();
    if !font.is_empty() {
        app.global::<Theme>().set_font(font.into());
    }
    theme::watch_theme(app.as_weak());

    let st = state::state();
    state::STATE.with(|s| *s.borrow_mut() = Some(st.clone()));
    let _ = fs::create_dir_all(st.borrow().store.runs_dir());
    st.borrow().store.prune_incomplete(600);
    st.borrow_mut().reload();
    app.set_host(
        format!(
            "{} · {}",
            scan::host(),
            env::var("USER").unwrap_or_default()
        )
        .into(),
    );
    state::refresh(&app);

    actions::wire(&app);
    scan::wire(&app);
    state::wire(&app);
    assistant::wire(&app);
    let _ai_ticker = assistant::poll_timer(&app);
    let _toast_ticker = state::toast_timer(&app);

    app.run()
}
