//! OmaPhoenix desktop app (Slint) on the same engine as the CLI and TUI.

mod activity;
mod audit;
mod backup;
mod migrate;
mod motion;
mod nav;
mod pulse;
mod run;
mod settings;
mod spring;
mod state;
mod theme;
mod timeline;

#[allow(
    unsafe_code,
    clippy::all,
    clippy::pedantic,
    clippy::unwrap_used,
    clippy::panic,
    missing_docs,
    unused_qualifications,
    reason = "generated by slint-build"
)]
mod ui {
    slint::include_modules!();
}

use phx_core::App as Engine;
use phx_core::migrate::Migration;
use phx_core::sys;
use secaudit_core::store::Store;
use slint::ComponentHandle;

use state::{quiet, ui_engine, ui_motion, ui_state, ui_timer};
use ui::{App, Theme};

fn main() -> Result<(), slint::PlatformError> {
    let app = App::new()?;
    // Matches omaphoenix.desktop, so the compositor shows its icon.
    slint::set_xdg_app_id("omaphoenix")?;
    // Fails only without $HOME; checked once here so ui_engine() can't.
    Engine::from_env(&quiet).map_err(|e| slint::PlatformError::Other(e.to_string()))?;
    if let Some(tokens) = theme::theme_file().and_then(|p| theme::read_tokens(&p)) {
        theme::apply_theme(&app, &tokens);
    }
    let font = sys::output(None, &["omarchy-font-current"]).unwrap_or_default();
    if !font.is_empty() {
        app.global::<Theme>().set_font(font.into());
    }
    theme::watch_theme(app.as_weak());

    let store = Store::from_env();
    let (state, motion, timer) = (ui_state(), ui_motion(), ui_timer());
    {
        let mut s = state.borrow_mut();
        s.accepted = store.accepted();
        s.audit = store.runs().into_iter().next();
        s.migration = Migration::load(&ui_engine().state_dir());
    }
    motion.borrow_mut().reduced = motion::reduced_motion();

    timeline::refresh_snapshots(&app, &ui_engine());
    settings::refresh_settings(&app, &ui_engine());
    audit::refresh_audit(&app, &state, &motion, &timer);
    migrate::refresh_migrate(&app, &state, &ui_engine());
    pulse::refresh_pulse(&app, &state);
    if ui_engine().repo.exists() {
        pulse::load_doctor(&app);
    }

    let _activity_watch = activity::watch(&app);
    if ui_engine().repo.exists() {
        backup::load_choices(&app);
        if !ui_engine().has_chosen() {
            app.set_section(3);
        }
    }
    activity::refresh(&app);

    nav::wire(&app);
    timeline::wire(&app);
    pulse::wire(&app);
    audit::wire(&app);
    backup::wire(&app);
    migrate::wire(&app);
    settings::wire(&app);

    app.run()
}
