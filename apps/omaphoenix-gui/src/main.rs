/// What the UI shows, kept on the UI thread.
#[derive(Default)]
struct Model {
    choices: Vec<(Choice, Vec<String>)>,
    audit: Option<Run>,
    accepted: BTreeMap<String, Accepted>,
    migration: Migration,
    preview: String,
}

type Shared = Rc<RefCell<Model>>;

// UI-thread state. Background results come back through
// `invoke_from_event_loop`, whose closures must be `Send`; they fetch these
// on arrival instead of capturing `Rc`s.
thread_local! {
    static STATE: Shared = Rc::new(RefCell::new(Model::default()));
    static MOTION: Rc<RefCell<Motion>> = Rc::new(RefCell::new(Motion {
        ring: Spring::new(0.0, GLIDE),
        drop: Spring::new(0.0, GLIDE),
        sheet: Spring::new(SHEET_H, SHEET),
        sheet_open: false,
        reduced: false,
        last: None,
        drag: Vec::new(),
        drag_start: SHEET_H,
    }));
    static TIMER: Rc<Timer> = Rc::new(Timer::default());
}

/// The engine, built where it's needed: it only reads the environment, and
/// holding one across threads would need its log callback to be `Sync`.
fn ui_engine() -> Engine<'static> {
    Engine::from_env(&quiet).unwrap_or_else(|_| Engine {
        home: PathBuf::new(),
        repo: phx_core::store::Repo {
            dir: PathBuf::new(),
        },
        log: &quiet,
        passphrase: None,
    })
}

fn ui_state() -> Shared {
    STATE.with(Rc::clone)
}

fn ui_motion() -> Rc<RefCell<Motion>> {
    MOTION.with(Rc::clone)
}

fn ui_timer() -> Rc<Timer> {
    TIMER.with(Rc::clone)
}

/// The `omaphoenix` CLI: next to this binary, else on PATH.
fn cli() -> String {
    env::current_exe()
        .ok()
        .and_then(|e| e.parent().map(|d| d.join("omaphoenix")))
        .filter(|p| p.exists())
        .map_or_else(
            || "omaphoenix".to_owned(),
            |p| p.to_string_lossy().into_owned(),
        )
}

/// Runs a shell command in a terminal window (sudo and passphrases need
/// one), then calls `done` on the UI thread.
fn in_terminal(app: &App, script: &str, done: impl FnOnce(&App) + Send + 'static) {
    if !sys::has("xdg-terminal-exec") {
        app.set_toast(format!("Run this in a terminal: {script}").into());
        return;
    }
    let full = format!("{script}; echo; read -rp 'Press Enter to close ' _");
    let child = sys::command("xdg-terminal-exec")
        .args(["bash", "-c", &full])
        .spawn();
    let weak = app.as_weak();
    match child {
        Ok(mut c) => {
            thread::spawn(move || {
                let _ = c.wait();
                let _ = slint::invoke_from_event_loop(move || {
                    if let Some(app) = weak.upgrade() {
                        done(&app);
                    }
                });
            });
        }
        Err(e) => app.set_toast(format!("Couldn't open a terminal: {e}").into()),
    }
}

/// Shell-quotes for the terminal script.
fn sq(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Runs `work` on a thread and `then` with its result on the UI thread.
fn background<T: Send + 'static>(
    app: &App,
    work: impl FnOnce() -> T + Send + 'static,
    then: impl FnOnce(&App, T) + Send + 'static,
) {
    let weak = app.as_weak();
    thread::spawn(move || {
        let out = work();
        let _ = slint::invoke_from_event_loop(move || {
            if let Some(app) = weak.upgrade() {
                then(&app, out);
            }
        });
    });
}

fn ago(iso: &str) -> String {
    let then = sys::output(None, &["date", "-d", iso, "+%s"])
        .ok()
        .and_then(|s| s.parse::<u64>().ok());
    let now = secaudit_core::store::now();
    match then.map(|t| now.saturating_sub(t)) {
        None => iso.to_owned(),
        Some(0..60) => "just now".into(),
        Some(s @ 60..3600) => format!("{} min ago", s / 60),
        Some(s @ 3600..172_800) => format!("{} h ago", s / 3600),
        Some(s) => format!("{} days ago", s / 86_400),
    }
}

fn model<T: Clone + 'static>(v: Vec<T>) -> ModelRc<T> {
    ModelRc::new(VecModel::from(v))
}

// ---------- refresh ----------

fn refresh_snapshots(app: &App, engine: &Engine<'_>) {
    let snaps = engine.repo.list().unwrap_or_default();
    app.set_set_up(engine.repo.exists());
    app.set_last_snapshot(
        snaps
            .first()
            .map_or_else(
                || "No snapshot yet".to_owned(),
                |s| format!("Last snapshot {} ({})", ago(&s.time), s.id),
            )
            .into(),
    );
    app.set_snaps(model(
        snaps
            .iter()
            .map(|s| Snap {
                id: s.id.as_str().into(),
                when: ago(&s.time).into(),
                note: s.subject.as_str().into(),
            })
            .collect(),
    ));
}

fn refresh_settings(app: &App, engine: &Engine<'_>) {
    let status = schedule::status();
    app.set_timer_on(!status.starts_with("timer off"));
    app.set_timer_status(status.into());
    app.set_repo_dir(engine.repo.dir.to_string_lossy().as_ref().into());
    app.set_remote(engine.repo.remote().into());
    app.set_secrets_ready(phx_core::category::secret::secrets_ready(&engine.repo.dir));
}

fn refresh_audit(app: &App, state: &Shared, motion: &Rc<RefCell<Motion>>, timer: &Rc<Timer>) {
    let s = state.borrow();
    let Some(run) = &s.audit else {
        app.set_audited(false);
        return;
    };
    let c = run.counts();
    app.set_audited(true);
    app.set_score(i32::try_from(c.score()).unwrap_or(0));
    app.set_fails(i32::try_from(c.fail).unwrap_or(0));
    app.set_warns(i32::try_from(c.warn).unwrap_or(0));
    app.set_accepted(i32::try_from(c.accepted).unwrap_or(0));
    let mut items: Vec<&secaudit_core::store::Item> =
        run.items.iter().filter(|i| i.is_issue()).collect();
    items.sort_by_key(|i| {
        (
            i.accepted,
            secaudit_core::store::sev_order(i.finding.sev),
            i.n,
        )
    });
    app.set_findings(model(
        items
            .iter()
            .map(|i| AuditRow {
                sev: secaudit_core::store::sev_name(i.finding.sev).into(),
                title: i.title().into(),
                section: i.finding.section.as_str().into(),
                detail: i.finding.detail.as_str().into(),
                fix: i.finding.fix.as_str().into(),
                hint: i.finding.hint.as_str().into(),
                accepted: i.accepted,
            })
            .collect(),
    ));
    #[allow(clippy::cast_precision_loss, reason = "a score of 0-100")]
    let target = c.score() as f32;
    let mut m = motion.borrow_mut();
    let reduced = m.reduced;
    m.ring.to(target, GLIDE, reduced);
    drop(m);
    kick(app, motion, timer);
    drop(s);
    refresh_pulse(app, state);
}

/// The headline and the one primary action, both derived from state
/// (DESIGN.md §1–2: never claim protection that isn't there).
fn refresh_pulse(app: &App, state: &Shared) {
    let s = state.borrow();
    let risks = app.get_doctor_risks();
    let (headline, sub) = if !app.get_set_up() {
        (
            "Nothing is protected yet.",
            "Set up snapshots, and a reinstall stops being a loss.",
        )
    } else if risks > 0 {
        (
            "Some of your setup would be lost in a reinstall.",
            "See what's at risk below, and take a snapshot.",
        )
    } else if risks == 0 {
        (
            "You're protected.",
            "A reinstall would lose nothing that matters.",
        )
    } else {
        ("Checking your protection…", "")
    };
    app.set_headline(headline.into());
    app.set_subline(sub.into());
    let fails = s.audit.as_ref().map_or(0, |r| r.counts().fail);
    let label = if !app.get_set_up() {
        "Set up snapshots".to_owned()
    } else if fails > 0 {
        format!(
            "Review {fails} audit risk{}",
            if fails == 1 { "" } else { "s" }
        )
    } else if s.migration.audited && s.migration.snapshot.is_empty() {
        "Continue migration".to_owned()
    } else {
        "Take snapshot".to_owned()
    };
    app.set_primary_label(label.into());
}

fn refresh_migrate(app: &App, state: &Shared, engine: &Engine<'_>) {
    let s = state.borrow();
    let done = s.migration.done();
    let remote = engine.repo.remote();
    app.set_steps(model(
        migrate::STEPS
            .iter()
            .enumerate()
            .map(|(i, t)| StepRow {
                title: (*t).into(),
                done: done.get(i).copied().unwrap_or(false),
                explain: migrate::explain(i, &remote).into(),
            })
            .collect(),
    ));
}

fn refresh_backup(app: &App, state: &Shared) {
    let s = state.borrow();
    app.set_cats(model(
        s.choices
            .iter()
            .map(|(c, _)| CatRow {
                name: c.category.as_str().into(),
                selected: i32::try_from(c.items.iter().filter(|(_, on)| *on).count()).unwrap_or(0),
                total: i32::try_from(c.items.len()).unwrap_or(0),
                note: SharedString::new(),
            })
            .collect(),
    ));
    let sel = usize::try_from(app.get_cat_sel()).ok();
    let items = sel
        .and_then(|i| s.choices.get(i))
        .map_or_else(Vec::new, |(c, notes)| {
            c.items
                .iter()
                .zip(notes)
                .map(|((id, on), note)| ItemRow {
                    id: id.as_str().into(),
                    on: *on,
                    note: note.as_str().into(),
                })
                .collect()
        });
    app.set_items(model(items));
}

fn load_doctor(app: &App) {
    background(
        app,
        || {
            Engine::from_env(&quiet)
                .map(|e| e.doctor())
                .unwrap_or_default()
        },
        |app, findings| {
            let risks = findings.iter().filter(|f| f.level == "risk").count();
            app.set_doctor_risks(i32::try_from(risks).unwrap_or(0));
            refresh_pulse(app, &ui_state());
        },
    );
}

fn load_choices(app: &App) {
    background(
        app,
        || {
            Engine::from_env(&quiet)
                .and_then(|e| e.choices())
                .map_err(|e| e.to_string())
        },
        |app, r| match r {
            Ok(c) => {
                let state = ui_state();
                state.borrow_mut().choices = c;
                refresh_backup(app, &state);
            }
            Err(e) => app.set_toast(e.into()),
        },
    );
}

fn set_busy(app: &App, what: &str) {
    app.set_busy(what.into());
}

// ---------- main ----------

#[allow(
    clippy::too_many_lines,
    reason = "wiring one callback per UI action, in one place"
)]
fn main() -> Result<(), slint::PlatformError> {
    let app = App::new()?;
    // Matches omaphoenix.desktop, so the compositor shows its icon.
    slint::set_xdg_app_id("omaphoenix")?;
    // Fails only without $HOME; checked once here so ui_engine() can't.
    Engine::from_env(&quiet).map_err(|e| slint::PlatformError::Other(e.to_string()))?;
    if let Some(tokens) = theme_file().and_then(|p| read_tokens(&p)) {
        apply_theme(&app, &tokens);
    }
    let font = sys::output(None, &["omarchy-font-current"]).unwrap_or_default();
    if !font.is_empty() {
        app.global::<Theme>().set_font(font.into());
    }
    watch_theme(app.as_weak());

    let store = Store::from_env();
    let (state, motion, timer) = (ui_state(), ui_motion(), ui_timer());
    {
        let mut s = state.borrow_mut();
        s.accepted = store.accepted();
        s.audit = store.runs().into_iter().next();
        s.migration = Migration::load(&ui_engine().state_dir());
    }
    motion.borrow_mut().reduced = reduced_motion();

    refresh_snapshots(&app, &ui_engine());
    refresh_settings(&app, &ui_engine());
    refresh_audit(&app, &state, &motion, &timer);
    refresh_migrate(&app, &state, &ui_engine());
    refresh_pulse(&app, &state);
    if ui_engine().repo.exists() {
        load_doctor(&app);
    }

    app.on_go({
        let (weak, state) = (app.as_weak(), state.clone());
        move |i| {
            let Some(app) = weak.upgrade() else { return };
            app.set_section(i);
            app.set_toast(SharedString::new());
            if i == 3 && state.borrow().choices.is_empty() {
                load_choices(&app);
            }
        }
    });

    let take_snapshot = {
        let weak = app.as_weak();
        move || {
            let Some(app) = weak.upgrade() else { return };
            if !app.get_set_up() {
                app.set_toast("Not set up yet: Settings → Set up snapshots".into());
                return;
            }
            set_busy(&app, "Taking a snapshot…");
            background(
                &app,
                || {
                    sys::command(&cli()).arg("snapshot").output().map(|o| {
                        String::from_utf8_lossy(&o.stdout)
                            .lines()
                            .last()
                            .unwrap_or_default()
                            .to_owned()
                    })
                },
                |app, r| {
                    use slint::Model as _;
                    let (motion, timer) = (ui_motion(), ui_timer());
                    set_busy(app, "");
                    let before = app.get_snaps().row_count();
                    refresh_snapshots(app, &ui_engine());
                    match r {
                        Ok(line) => app.set_toast(line.into()),
                        Err(e) => app.set_toast(format!("Snapshot failed: {e}").into()),
                    }
                    // FLIP: the new row starts one row up and settles in;
                    // the offset changes in the same frame as the insert.
                    if app.get_snaps().row_count() > before {
                        let mut m = motion.borrow_mut();
                        m.drop.set(-ROW);
                        app.set_drop(-ROW);
                        let reduced = m.reduced;
                        m.drop.to(0.0, GLIDE, reduced);
                        drop(m);
                        kick(app, &motion, &timer);
                    }
                },
            );
        }
    };
    app.on_take_snapshot(take_snapshot.clone());

    app.on_primary({
        let (weak, take) = (app.as_weak(), take_snapshot.clone());
        move || {
            let Some(app) = weak.upgrade() else { return };
            let label = app.get_primary_label();
            if label.starts_with("Review") {
                app.invoke_go(2);
            } else if label.starts_with("Continue") {
                app.invoke_go(4);
            } else if label.starts_with("Set up") {
                app.invoke_set_up_repo();
            } else {
                take();
            }
        }
    });

    app.on_open_preview({
        let (weak, motion, timer, state) =
            (app.as_weak(), motion.clone(), timer.clone(), state.clone());
        move |id| {
            let Some(app) = weak.upgrade() else { return };
            state.borrow_mut().preview = id.to_string();
            app.set_preview_id(id.clone());
            app.set_rows_loaded(false);
            app.set_rows(model(Vec::new()));
            app.set_sheet_visible(true);
            {
                let mut m = motion.borrow_mut();
                m.sheet_open = true;
                let reduced = m.reduced;
                m.sheet.to(0.0, SHEET, reduced);
            }
            kick(&app, &motion, &timer);
            let at = id.to_string();
            background(
                &app,
                move || {
                    let opt = phx_core::RestoreOptions {
                        at,
                        dry_run: true,
                        ..Default::default()
                    };
                    ui_engine()
                        .restore(&opt)
                        .map(|(_, reports)| reports)
                        .map_err(|e| e.to_string())
                },
                |app, r| {
                    app.set_rows_loaded(true);
                    match r {
                        Ok(reports) => app.set_rows(model(
                            reports
                                .iter()
                                .filter(|r| !r.result.planned.is_empty())
                                .map(|r| PreviewRow {
                                    category: r.category.into(),
                                    count: i32::try_from(r.result.planned.len()).unwrap_or(0),
                                    detail: r
                                        .result
                                        .planned
                                        .first()
                                        .map(String::as_str)
                                        .unwrap_or_default()
                                        .into(),
                                })
                                .collect(),
                        )),
                        Err(e) => app.set_toast(e.into()),
                    }
                },
            );
        }
    });

    let close_preview = {
        let (weak, motion, timer) = (app.as_weak(), motion.clone(), timer.clone());
        move || {
            let Some(app) = weak.upgrade() else { return };
            {
                let mut m = motion.borrow_mut();
                m.sheet_open = false;
                let reduced = m.reduced;
                m.sheet.to(SHEET_H, SHEET, reduced);
            }
            kick(&app, &motion, &timer);
        }
    };
    app.on_close_preview(close_preview.clone());

    app.on_drag_sheet({
        let (weak, motion) = (app.as_weak(), motion.clone());
        move |dy| {
            let Some(app) = weak.upgrade() else { return };
            let mut m = motion.borrow_mut();
            if m.drag.is_empty() {
                m.drag_start = m.sheet.value;
            }
            let y = (m.drag_start + dy).max(0.0);
            m.sheet.set(y);
            m.drag.push((Instant::now(), y));
            app.set_sheet_y(y);
        }
    });

    app.on_release_sheet({
        let (weak, motion, timer, close) = (
            app.as_weak(),
            motion.clone(),
            timer.clone(),
            close_preview.clone(),
        );
        move || {
            let Some(app) = weak.upgrade() else { return };
            let mut m = motion.borrow_mut();
            let v = match (m.drag.first(), m.drag.last()) {
                (Some(a), Some(b)) if b.0 > a.0 => (b.1 - a.1) / (b.0 - a.0).as_secs_f32(),
                _ => 0.0,
            };
            m.drag.clear();
            let closing = m.sheet.value > SHEET_H * 0.35 || v > 900.0;
            if closing {
                drop(m);
                close();
                return;
            }
            let reduced = m.reduced;
            m.sheet.fling(v, 0.0, SHEET, reduced);
            drop(m);
            kick(&app, &motion, &timer);
        }
    });

    app.on_apply_restore({
        let (weak, state, close) = (app.as_weak(), state.clone(), close_preview.clone());
        move || {
            let Some(app) = weak.upgrade() else { return };
            let id = state.borrow().preview.clone();
            close();
            in_terminal(
                &app,
                &format!("{} restore --at {}", sq(&cli()), sq(&id)),
                |app| {
                    refresh_snapshots(app, &ui_engine());
                    app.set_toast(
                        "Restore finished in the terminal; replaced files are kept as .pre-restore"
                            .into(),
                    );
                },
            );
        }
    });

    app.on_scan({
        let weak = app.as_weak();
        move || {
            let Some(app) = weak.upgrade() else { return };
            set_busy(&app, "Auditing (quick, no sudo)…");
            background(
                &app,
                || {
                    let ctx = secaudit_core::audit::Ctx::from_env();
                    let host = fs::read_to_string("/proc/sys/kernel/hostname").unwrap_or_default();
                    let kernel =
                        fs::read_to_string("/proc/sys/kernel/osrelease").unwrap_or_default();
                    let store = Store::from_env();
                    let dir = store.record_quick_scan(
                        &ctx,
                        host.trim(),
                        kernel.trim(),
                        &phx_core::category::stamp(),
                    );
                    dir.map(|d| store.runs().into_iter().find(|r| r.path == d))
                        .map_err(|e| e.to_string())
                },
                |app, r| {
                    let (state, motion, timer) = (ui_state(), ui_motion(), ui_timer());
                    set_busy(app, "");
                    match r {
                        Ok(run) => {
                            {
                                let mut s = state.borrow_mut();
                                s.audit = run;
                                if !s.migration.audited {
                                    s.migration.audited = true;
                                    s.migration.save(&ui_engine().state_dir());
                                }
                            }
                            app.set_finding_sel(0);
                            refresh_audit(app, &state, &motion, &timer);
                            refresh_migrate(app, &state, &ui_engine());
                            app.set_toast(format!("Audit done: score {}", app.get_score()).into());
                        }
                        Err(e) => app.set_toast(format!("Audit failed: {e}").into()),
                    }
                },
            );
        }
    });

    app.on_toggle_accept({
        let (weak, state, motion, timer) =
            (app.as_weak(), state.clone(), motion.clone(), timer.clone());
        move |i| {
            let Some(app) = weak.upgrade() else { return };
            let Ok(i) = usize::try_from(i) else { return };
            {
                let mut s = state.borrow_mut();
                let Some(run) = &s.audit else { return };
                let mut items: Vec<&secaudit_core::store::Item> =
                    run.items.iter().filter(|x| x.is_issue()).collect();
                items.sort_by_key(|x| {
                    (
                        x.accepted,
                        secaudit_core::store::sev_order(x.finding.sev),
                        x.n,
                    )
                });
                let Some(item) = items.get(i) else { return };
                let (key, was, title, section) = (
                    item.accept_key(),
                    item.accepted,
                    item.title().to_owned(),
                    item.finding.section.clone(),
                );
                if was {
                    s.accepted.remove(&key);
                } else {
                    s.accepted.insert(
                        key,
                        Accepted {
                            section,
                            msg: title,
                            at: secaudit_core::store::now(),
                        },
                    );
                }
                let accepted = s.accepted.clone();
                if let Err(e) = Store::from_env().save_accepted(&accepted) {
                    app.set_toast(format!("Couldn't save: {e}").into());
                    return;
                }
                if let Some(run) = &mut s.audit {
                    run.recount(&accepted);
                }
            }
            refresh_audit(&app, &state, &motion, &timer);
        }
    });

    app.on_run_fix({
        let weak = app.as_weak();
        move |i| {
            let Some(app) = weak.upgrade() else { return };
            let fix = usize::try_from(i)
                .ok()
                .and_then(|i| slint::Model::row_data(&app.get_findings(), i))
                .map(|f| f.fix.to_string());
            if let Some(fix) = fix.filter(|f| !f.is_empty()) {
                // Fixes always confirm (AGENTS.md): the terminal shows the
                // command and runs it only on y.
                let script = format!(
                    "echo; echo '  $ '{q}; echo; read -rp '  Run this fix now? [y/N] ' a; [[ $a == [yY]* ]] && bash -c {q}",
                    q = sq(&fix)
                );
                in_terminal(&app, &script, |app| {
                    app.set_toast("Scan again to confirm the fix worked".into());
                });
            }
        }
    });

    app.on_select_cat({
        let (weak, state) = (app.as_weak(), state.clone());
        move |i| {
            let Some(app) = weak.upgrade() else { return };
            app.set_cat_sel(i);
            refresh_backup(&app, &state);
        }
    });

    app.on_toggle_cat({
        let (weak, state) = (app.as_weak(), state.clone());
        move |i| {
            let Some(app) = weak.upgrade() else { return };
            if let Ok(idx) = usize::try_from(i) {
                let mut s = state.borrow_mut();
                if let Some((c, _)) = s.choices.get_mut(idx) {
                    let all = c.items.iter().all(|(_, on)| *on);
                    c.items.iter_mut().for_each(|(_, on)| *on = !all);
                }
            }
            app.set_backup_dirty(true);
            refresh_backup(&app, &state);
        }
    });

    app.on_toggle_item({
        let (weak, state) = (app.as_weak(), state.clone());
        move |i| {
            let Some(app) = weak.upgrade() else { return };
            let (Ok(cat), Ok(i)) = (usize::try_from(app.get_cat_sel()), usize::try_from(i)) else {
                return;
            };
            if let Some((_, on)) = state
                .borrow_mut()
                .choices
                .get_mut(cat)
                .and_then(|(c, _)| c.items.get_mut(i))
            {
                *on = !*on;
            }
            app.set_backup_dirty(true);
            refresh_backup(&app, &state);
        }
    });

    app.on_save_backup({
        let (weak, state) = (app.as_weak(), state.clone());
        move || {
            let Some(app) = weak.upgrade() else { return };
            let plain: Vec<Choice> = state
                .borrow()
                .choices
                .iter()
                .map(|(c, _)| c.clone())
                .collect();
            match ui_engine().save_choices(&plain) {
                Ok(()) => {
                    app.set_backup_dirty(false);
                    app.set_toast("Saved: the next snapshot captures exactly this".into());
                }
                Err(e) => app.set_toast(format!("Save failed: {e}").into()),
            }
        }
    });

    app.on_migrate_step({
        let (weak, state, take) = (app.as_weak(), state.clone(), take_snapshot.clone());
        move |i| {
            let Some(app) = weak.upgrade() else { return };
            match i {
                0 => {
                    app.invoke_go(2);
                    app.invoke_scan();
                }
                4 => {
                    set_busy(&app, "Re-auditing against the restored snapshot…");
                    background(
                        &app,
                        || {
                            sys::command(&cli()).arg("reaudit").output().map(|o| {
                                String::from_utf8_lossy(&if o.stdout.is_empty() {
                                    o.stderr
                                } else {
                                    o.stdout
                                })
                                .lines()
                                .take(4)
                                .collect::<Vec<_>>()
                                .join(" · ")
                            })
                        },
                        |app, r| {
                            set_busy(app, "");
                            app.set_toast(r.unwrap_or_else(|e| e.to_string()).into());
                        },
                    );
                }
                1 => {
                    let mut s = state.borrow_mut();
                    s.migration.cleaned = true;
                    s.migration.save(&ui_engine().state_dir());
                    drop(s);
                    app.invoke_go(2);
                }
                2 => {
                    take();
                    if let Some(id) = ui_engine()
                        .repo
                        .list()
                        .ok()
                        .and_then(|l| l.first().map(|s| s.id.clone()))
                    {
                        let mut s = state.borrow_mut();
                        s.migration.snapshot = id;
                        s.migration.save(&ui_engine().state_dir());
                    }
                }
                _ => {
                    let mut s = state.borrow_mut();
                    s.migration.restored_note_seen = true;
                    s.migration.save(&ui_engine().state_dir());
                }
            }
            refresh_migrate(&app, &state, &ui_engine());
            refresh_pulse(&app, &state);
        }
    });

    app.on_toggle_timer({
        let weak = app.as_weak();
        move || {
            let Some(app) = weak.upgrade() else { return };
            let r = if app.get_timer_on() {
                schedule::off()
            } else {
                schedule::on("30m")
            };
            if let Err(e) = r {
                app.set_toast(e.into());
            }
            refresh_settings(&app, &ui_engine());
        }
    });

    app.on_setup_secrets({
        let weak = app.as_weak();
        move || {
            let Some(app) = weak.upgrade() else { return };
            in_terminal(&app, &format!("{} secrets init", sq(&cli())), |app| {
                refresh_settings(app, &ui_engine());
            });
        }
    });

    app.on_set_up_repo({
        let weak = app.as_weak();
        move || {
            let Some(app) = weak.upgrade() else { return };
            in_terminal(&app, &format!("{} init", sq(&cli())), |app| {
                refresh_snapshots(app, &ui_engine());
                refresh_settings(app, &ui_engine());
            });
        }
    });

    app.run()
}
