// ---------- theme (DESIGN.md §5.1), as in omaphoenix-gui ----------

const TOKEN_MAP: &[(&str, &[&str])] = &[
    ("surface-base", &["background"]),
    ("surface-sunken", &["dark_background", "background"]),
    (
        "surface-deep",
        &["darker_background", "dark_background", "background"],
    ),
    (
        "surface-raised",
        &["lighter_background", "selection", "background"],
    ),
    ("text-primary", &["foreground"]),
    ("text-secondary", &["light_foreground", "foreground"]),
    ("text-muted", &["muted", "dark_foreground", "foreground"]),
    ("accent", &["accent", "blue"]),
    ("selection", &["selection", "lighter_background"]),
    ("state-risk", &["red"]),
    ("state-attention", &["yellow"]),
    ("state-fine", &["green"]),
    ("state-info", &["cyan", "blue"]),
];

fn theme_file() -> Option<PathBuf> {
    let state = env::var_os("XDG_STATE_HOME")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .or_else(|| env::var_os("HOME").map(|h| Path::new(&h).join(".local/state")))?;
    Some(state.join("omarchy/current/theme/colors.toml"))
}

fn parse_hex(s: &str) -> Option<slint::Color> {
    let s = s.trim().strip_prefix('#')?;
    let byte = |i: usize| s.get(i..i + 2).and_then(|b| u8::from_str_radix(b, 16).ok());
    Some(slint::Color::from_rgb_u8(byte(0)?, byte(2)?, byte(4)?))
}

fn read_tokens(path: &Path) -> Option<BTreeMap<&'static str, slint::Color>> {
    let table: toml::Table = fs::read_to_string(path).ok()?.parse().ok()?;
    let hex = |k: &str| {
        table
            .get(k)
            .and_then(toml::Value::as_str)
            .and_then(parse_hex)
    };
    Some(
        TOKEN_MAP
            .iter()
            .filter_map(|(token, keys)| keys.iter().find_map(|k| hex(k)).map(|c| (*token, c)))
            .collect(),
    )
}

fn apply_theme(app: &App, tokens: &BTreeMap<&'static str, slint::Color>) {
    let t = app.global::<Theme>();
    for (k, c) in tokens {
        match *k {
            "surface-base" => t.set_surface_base(*c),
            "surface-sunken" => t.set_surface_sunken(*c),
            "surface-deep" => t.set_surface_deep(*c),
            "surface-raised" => t.set_surface_raised(*c),
            "text-primary" => t.set_text_primary(*c),
            "text-secondary" => t.set_text_secondary(*c),
            "text-muted" => t.set_text_muted(*c),
            "accent" => t.set_accent(*c),
            "selection" => t.set_selection(*c),
            "state-risk" => t.set_state_risk(*c),
            "state-attention" => t.set_state_attention(*c),
            "state-fine" => t.set_state_fine(*c),
            "state-info" => t.set_state_info(*c),
            _ => {}
        }
    }
}

/// Follows Omarchy theme switches (the `current/theme` symlink is swapped).
fn watch_theme(app: Weak<App>) {
    thread::spawn(move || {
        let stamp = |p: &Path| -> Option<(PathBuf, SystemTime)> {
            let real = fs::canonicalize(p).ok()?;
            Some((real.clone(), fs::metadata(&real).ok()?.modified().ok()?))
        };
        let Some(path) = theme_file() else { return };
        let mut last = stamp(&path);
        loop {
            thread::sleep(Duration::from_millis(400));
            let now = stamp(&path);
            if now == last {
                continue;
            }
            last = now;
            if let Some(tokens) = read_tokens(&path) {
                let app = app.clone();
                let _ = slint::invoke_from_event_loop(move || {
                    if let Some(app) = app.upgrade() {
                        apply_theme(&app, &tokens);
                    }
                });
            }
        }
    });
}

// ---------- state ----------

/// Tabs, as `in_tab()` in the terminal app.
fn in_tab(tab: i32, f: &Item) -> bool {
    let sev = sev_name(f.finding.sev);
    match tab {
        0 => f.is_issue() && !f.accepted,
        1 => f.accepted,
        2 => matches!(sev, "info" | "skip"),
        3 => sev == "pass",
        _ => true,
    }
}

struct State {
    store: Store,
    runs: Vec<Run>,
    current: usize,
    accepted: BTreeMap<String, Accepted>,
    /// Line numbers (`Item::n`) behind the rows on screen.
    shown: Vec<usize>,
    toast_until: Option<Instant>,
    /// History row armed for deletion, and until when.
    delete_armed: Option<(usize, Instant)>,
}

impl State {
    fn run(&self) -> Option<&Run> {
        self.runs.get(self.current)
    }

    fn reload(&mut self) {
        self.accepted = self.store.accepted();
        self.runs = self.store.runs();
        for r in &mut self.runs {
            r.recount(&self.accepted);
        }
        self.current = self.current.min(self.runs.len().saturating_sub(1));
    }
}

type Shared = Rc<RefCell<State>>;

thread_local! {
    static STATE: RefCell<Option<Shared>> = const { RefCell::new(None) };
}

fn state() -> Shared {
    STATE.with(|s| s.borrow().clone()).unwrap_or_else(|| {
        Rc::new(RefCell::new(State {
            store: Store::from_env(),
            runs: Vec::new(),
            current: 0,
            accepted: BTreeMap::new(),
            shown: Vec::new(),
            toast_until: None,
            delete_armed: None,
        }))
    })
}

fn model<T: Clone + 'static>(v: Vec<T>) -> ModelRc<T> {
    ModelRc::new(Rc::new(VecModel::from(v)))
}

fn int(n: usize) -> i32 {
    i32::try_from(n).unwrap_or(i32::MAX)
}

/// `date -d @epoch +fmt`: local time without a time-zone crate.
fn local(epoch: u64, fmt: &str) -> String {
    Command::new("date")
        .args(["-d", &format!("@{epoch}"), &format!("+{fmt}")])
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_default()
}

fn toast(app: &App, msg: impl Into<SharedString>) {
    app.set_toast(msg.into());
    state().borrow_mut().toast_until = Some(Instant::now() + Duration::from_secs(5));
}

/// Puts the current run, tab and search on screen.
fn refresh(app: &App) {
    let shared = state();
    let mut s = shared.borrow_mut();
    let Some(run) = s.run() else {
        app.set_has_run(false);
        app.set_history(model(Vec::new()));
        return;
    };
    let c = run.counts();
    app.set_has_run(true);
    let latest = s.current == 0;
    app.set_when(
        format!(
            "{} · {} scan{}",
            local(run.meta.started, "%a %-d %b %H:%M"),
            run.meta.mode,
            if latest { "" } else { " (older scan)" }
        )
        .into(),
    );
    let score = c.score();
    app.set_score(i32::try_from(score).unwrap_or(0));
    app.set_grade(c.grade().to_string().into());
    #[allow(clippy::cast_precision_loss, reason = "a score of 0-100")]
    app.set_ring(score as f32);
    app.set_fails(int(c.fail));
    app.set_warns(int(c.warn));
    app.set_passes(int(c.pass));
    app.set_notes(int(c.info + c.skip));
    app.set_accepted(int(c.accepted));
    app.set_tabs(model(vec![
        format!("Issues {}", c.fail + c.warn).into(),
        format!("Accepted {}", c.accepted).into(),
        format!("Notes {}", c.info + c.skip).into(),
        format!("Passed {}", c.pass).into(),
        format!("All {}", run.items.len()).into(),
    ]));
    let since = match s.runs.get(s.current + 1) {
        Some(prev) => {
            let (a, b) = (run.issue_keys(), prev.issue_keys());
            format!(
                "Since the previous scan: {} new · {} resolved",
                a.difference(&b).count(),
                b.difference(&a).count()
            )
        }
        None => "First scan on record".into(),
    };
    app.set_since(since.into());

    let q = app.get_query().to_lowercase();
    let tab = app.get_tab();
    let applied = run.applied();
    let mut items: Vec<&Item> = run
        .items
        .iter()
        .filter(|f| in_tab(tab, f))
        .filter(|f| {
            let fd = &f.finding;
            q.is_empty()
                || format!(
                    "{}\n{}\n{}\n{}\n{}",
                    fd.msg, fd.section, fd.detail, fd.fix, fd.hint
                )
                .to_lowercase()
                .contains(&q)
        })
        .collect();
    items.sort_by_key(|f| (sev_order(f.finding.sev), f.n));
    let rows: Vec<Row> = items
        .iter()
        .map(|f| Row {
            sev: sev_name(f.finding.sev).into(),
            title: f.title().into(),
            section: f.finding.section.as_str().into(),
            detail: f.finding.detail.as_str().into(),
            fix: f.finding.fix.as_str().into(),
            hint: f.finding.hint.as_str().into(),
            accepted: f.accepted,
            applied: applied.contains(&f.n),
        })
        .collect();
    s.shown = items.iter().map(|f| f.n).collect();
    let n = rows.len();
    app.set_rows(model(rows));
    app.set_sel(app.get_sel().min(int(n.saturating_sub(1))).max(0));

    set_history(app, &s);
}

/// The history sheet: every scan, newest first, compared with the one before.
fn set_history(app: &App, state: &State) {
    let history: Vec<Past> = state
        .runs
        .iter()
        .enumerate()
        .map(|(i, r)| {
            let c = r.counts();
            let change = match state.runs.get(i + 1) {
                Some(p) => {
                    let (a, b) = (r.issue_keys(), p.issue_keys());
                    format!(
                        "+{} new  −{} resolved",
                        a.difference(&b).count(),
                        b.difference(&a).count()
                    )
                }
                None => "first scan".into(),
            };
            Past {
                label: local(r.meta.started, "%a %-d %b %H:%M").into(),
                score: i32::try_from(c.score()).unwrap_or(0),
                grade: c.grade().to_string().into(),
                mode: r.meta.mode.as_str().into(),
                change: change.into(),
            }
        })
        .collect();
    app.set_history(model(history));
}

/// The selected finding of the current run.
fn selected(app: &App) -> Option<(PathBuf, Item)> {
    let st = state();
    let s = st.borrow();
    let n = *s.shown.get(usize::try_from(app.get_sel()).ok()?)?;
    let run = s.run()?;
    Some((
        run.path.clone(),
        run.items.iter().find(|i| i.n == n)?.clone(),
    ))
}

// ---------- actions ----------

/// The engine: `secaudit` next to this binary, else on PATH.
fn engine() -> String {
    env::current_exe()
        .ok()
        .and_then(|e| e.parent().map(|d| d.join("secaudit")))
        .filter(|p| p.exists())
        .map_or_else(
            || "secaudit".to_owned(),
            |p| p.to_string_lossy().into_owned(),
        )
}

fn sq(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Runs a shell script in a terminal window, then `done` on the UI thread.
fn in_terminal(app: &App, script: &str, done: impl FnOnce(&App) + Send + 'static) {
    let full = format!("{script}; echo; read -rp 'Press Enter to close ' _");
    let child = Command::new("xdg-terminal-exec")
        .args(["--title=Security Audit", "bash", "-c", &full])
        .spawn();
    let weak = app.as_weak();
    match child {
        Ok(mut c) => {
            thread::spawn(move || {
                let _ = c.wait();
                let _ = slint::invoke_from_event_loop(move || {
                    if let Some(app) = weak.upgrade() {
                        done(&app);
                    }
                });
            });
        }
        Err(_) => toast(
            app,
            format!("No terminal to run this in; run it yourself: {script}"),
        ),
    }
}

fn host() -> String {
    fs::read_to_string("/proc/sys/kernel/hostname")
        .unwrap_or_default()
        .trim()
        .to_owned()
}

fn stamp() -> String {
    local(now(), "%Y%m%d-%H%M%S")
}

fn scan(app: &App, mode: &str) {
    let mode = if mode == "again" {
        state()
            .borrow()
            .run()
            .map_or_else(|| "quick".to_owned(), |r| r.meta.mode.clone())
    } else {
        mode.to_owned()
    };
    if !app.get_busy().is_empty() {
        return;
    }
    let store = state().borrow().store.clone();
    let kernel = fs::read_to_string("/proc/sys/kernel/osrelease")
        .unwrap_or_default()
        .trim()
        .to_owned();
    if mode == "quick" {
        app.set_busy("Scanning…".into());
        let weak = app.as_weak();
        thread::spawn(move || {
            let result = store.record_quick_scan(&Ctx::from_env(), &host(), &kernel, &stamp());
            let _ = slint::invoke_from_event_loop(move || {
                let Some(app) = weak.upgrade() else { return };
                app.set_busy(SharedString::new());
                match result {
                    Ok(_) => scan_done(&app),
                    Err(e) => toast(&app, format!("Scan failed: {e}")),
                }
            });
        });
        return;
    }
    // Full and deep: sudo asks in a terminal, the engine writes the run.
    let mut meta = Meta {
        mode: mode.clone(),
        started: now(),
        host: host(),
        user: env::var("USER").unwrap_or_default(),
        kernel,
        finished: None,
    };
    let dir = match store.begin(&stamp(), &meta) {
        Ok(d) => d,
        Err(e) => return toast(app, format!("Couldn't start the scan: {e}")),
    };
    let deep = if mode == "deep" { " --deep" } else { "" };
    let script = format!(
        "echo; echo '  Security Audit · {mode} scan'; echo '  Reads root-only files; never changes anything. sudo is only used to look.'; echo; sudo {}{deep} --json {} --user {} 2>&1 | tee {}",
        sq(&engine()),
        sq(&dir.join("findings.jsonl").to_string_lossy()),
        sq(&env::var("USER").unwrap_or_default()),
        sq(&dir.join("output.txt").to_string_lossy()),
    );
    app.set_busy(format!("{mode} scan in the terminal…").into());
    in_terminal(app, &script, move |app| {
        app.set_busy(SharedString::new());
        if fs::metadata(dir.join("findings.jsonl")).map_or(0, |m| m.len()) == 0 {
            let _ = fs::remove_dir_all(&dir);
            return toast(app, "Scan cancelled or failed; nothing was saved");
        }
        let _ = store.finish(&dir, &mut meta);
        scan_done(app);
    });
}

fn scan_done(app: &App) {
    let st = state();
    st.borrow_mut().reload();
    st.borrow_mut().current = 0;
    app.set_tab(0);
    app.set_sel(0);
    refresh(app);
    // The counts are copied out so no borrow is held while toast() writes.
    let counts = st.borrow().run().map(Run::counts);
    if let Some(c) = counts {
        let body = format!(
            "Score {} ({}) · {} fail · {} warn",
            c.score(),
            c.grade(),
            c.fail,
            c.warn
        );
        let _ = Command::new("notify-send")
            .args([
                "-a",
                "secaudit",
                "-i",
                "security-high-symbolic",
                "Security audit finished",
                &body,
            ])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn();
        toast(app, format!("Scan finished: {body}"));
    }
}

fn toggle_accept(app: &App) {
    let Some((_, item)) = selected(app) else {
        return;
    };
    if !item.is_issue() {
        return;
    }
    let st = state();
    let mut s = st.borrow_mut();
    let key = item.accept_key();
    let msg = if item.accepted {
        s.accepted.remove(&key);
        format!(
            "Moved back to Issues: {}. Press a again to undo.",
            item.title()
        )
    } else {
        s.accepted.insert(
            key,
            Accepted {
                section: item.finding.section.clone(),
                msg: item.title().to_owned(),
                at: now(),
            },
        );
        format!(
            "Accepted, no longer scored: {}. Press a again to undo.",
            item.title()
        )
    };
    if let Err(e) = s.store.save_accepted(&s.accepted) {
        drop(s);
        return toast(app, format!("Couldn't save: {e}"));
    }
    let acc = s.accepted.clone();
    for r in &mut s.runs {
        r.recount(&acc);
    }
    drop(s);
    refresh(app);
    toast(app, msg);
}

fn copy(app: &App) {
    let Some((_, item)) = selected(app) else {
        return;
    };
    let (text, what) = if item.finding.fix.is_empty() {
        (item.finding.hint, "Advice")
    } else {
        (item.finding.fix, "Fix command")
    };
    if text.is_empty() {
        return;
    }
    let ok = Command::new("wl-copy")
        .stdin(Stdio::piped())
        .spawn()
        .ok()
        .and_then(|mut c| {
            c.stdin.take()?.write_all(text.as_bytes()).ok()?;
            c.wait().ok()
        })
        .is_some_and(|s| s.success());
    toast(
        app,
        if ok {
            format!("{what} copied")
        } else {
            "wl-copy isn't available to copy with".into()
        },
    );
}

/// Runs the fix in a terminal after the user confirms there (it always
/// asks; AGENTS.md), and records it as applied when it succeeds.
fn run_fix(app: &App) {
    let Some((run_dir, item)) = selected(app) else {
        return;
    };
    if item.finding.fix.is_empty() || item.accepted {
        return toast(
            app,
            "No automatic fix for this finding. See How to address.",
        );
    }
    let status = env::temp_dir().join(format!(
        "secaudit-gui-fix-{}-{}",
        std::process::id(),
        item.n
    ));
    let _ = fs::remove_file(&status);
    let script = format!(
        "echo; echo '  '{title}; echo; echo '  $ '{fix}; echo; read -rp '  Run this fix now? [y/N] ' a; if [[ $a == [yY]* ]]; then echo; bash -c {fix}; echo $? > {st}; fi",
        title = sq(item.title()),
        fix = sq(&item.finding.fix),
        st = sq(&status.to_string_lossy()),
    );
    let n = item.n;
    in_terminal(app, &script, move |app| {
        let code = fs::read_to_string(&status)
            .ok()
            .map(|s| s.trim().to_owned());
        let _ = fs::remove_file(&status);
        match code.as_deref() {
            Some("0") => {
                if let Ok(run) = Run::load(&run_dir, &BTreeMap::new()) {
                    let _ = run.mark_applied(n);
                }
                state().borrow_mut().reload();
                refresh(app);
                toast(app, "Fix applied. Rescan (R) to confirm the issue is gone.");
            }
            Some(c) => toast(app, format!("The fix exited with status {c}")),
            None => toast(app, "Fix not run"),
        }
    });
}

fn export(app: &App) {
    let st = state();
    let s = st.borrow();
    let Some(run) = s.run() else { return };
    match run.export_markdown(&local(run.meta.started, "%Y-%m-%d %H:%M")) {
        Ok(p) => {
            let home = env::var("HOME").unwrap_or_default();
            let shown = p.to_string_lossy().replacen(&home, "~", 1);
            drop(s);
            toast(app, format!("Report saved: {shown}"));
        }
        Err(e) => {
            drop(s);
            toast(app, format!("Couldn't save the report: {e}"));
        }
    }
}

/// Deleting a scan asks first: the first click arms, a second within five
/// seconds deletes (DESIGN.md: never discard without asking).
fn delete_run(app: &App, i: usize) {
    let st = state();
    let armed = st
        .borrow()
        .delete_armed
        .is_some_and(|(j, until)| j == i && Instant::now() < until);
    if !armed {
        st.borrow_mut().delete_armed = Some((i, Instant::now() + Duration::from_secs(5)));
        let label = st
            .borrow()
            .runs
            .get(i)
            .map(|r| local(r.meta.started, "%a %-d %b %H:%M"))
            .unwrap_or_default();
        return toast(
            app,
            format!("Press Delete again to remove the scan from {label}"),
        );
    }
    let path = st.borrow().runs.get(i).map(|r| r.path.clone());
    if let Some(p) = path {
        let _ = fs::remove_dir_all(p);
    }
    st.borrow_mut().delete_armed = None;
    st.borrow_mut().reload();
    refresh(app);
    toast(app, "Scan deleted");
}

fn main() -> Result<(), slint::PlatformError> {
    let app = App::new()?;
    slint::set_xdg_app_id("secaudit-gui")?;
    if let Some(tokens) = theme_file().and_then(|p| read_tokens(&p)) {
        apply_theme(&app, &tokens);
    }
    let font = Command::new("omarchy-font-current")
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_default();
    if !font.is_empty() {
        app.global::<Theme>().set_font(font.into());
    }
    watch_theme(app.as_weak());

    let st = state();
    STATE.with(|s| *s.borrow_mut() = Some(st.clone()));
    let _ = fs::create_dir_all(st.borrow().store.runs_dir());
    st.borrow().store.prune_incomplete(600);
    st.borrow_mut().reload();
    app.set_host(format!("{} · {}", host(), env::var("USER").unwrap_or_default()).into());
    refresh(&app);

    let weak = app.as_weak();
    let on = move |f: fn(&App)| {
        let weak = weak.clone();
        move || {
            if let Some(app) = weak.upgrade() {
                f(&app);
            }
        }
    };
    app.on_toggle_accept({
        let f = on(toggle_accept);
        move |_| f()
    });
    app.on_copy({
        let f = on(copy);
        move |_| f()
    });
    app.on_run_fix({
        let f = on(run_fix);
        move |_| f()
    });
    app.on_export(on(export));
    let weak = app.as_weak();
    app.on_scan(move |mode| {
        if let Some(app) = weak.upgrade() {
            scan(&app, &mode);
        }
    });
    let weak = app.as_weak();
    app.on_set_tab(move |t| {
        if let Some(app) = weak.upgrade() {
            app.set_tab(t);
            app.set_sel(0);
            refresh(&app);
        }
    });
    let weak = app.as_weak();
    app.on_search(move |q| {
        if let Some(app) = weak.upgrade() {
            app.set_query(q);
            app.set_sel(0);
            refresh(&app);
        }
    });
    let weak = app.as_weak();
    app.on_open_run(move |i| {
        if let Some(app) = weak.upgrade() {
            state().borrow_mut().current = usize::try_from(i).unwrap_or(0);
            app.set_sel(0);
            refresh(&app);
        }
    });
    let weak = app.as_weak();
    app.on_delete_run(move |i| {
        if let Some(app) = weak.upgrade() {
            delete_run(&app, usize::try_from(i).unwrap_or(0));
        }
    });

    // Toasts fade after five seconds.
    let ticker = Timer::default();
    let weak = app.as_weak();
    ticker.start(TimerMode::Repeated, Duration::from_millis(500), move || {
        let Some(app) = weak.upgrade() else { return };
        let expired = state()
            .borrow()
            .toast_until
            .is_some_and(|t| Instant::now() >= t);
        if expired {
            state().borrow_mut().toast_until = None;
            app.set_toast(SharedString::new());
        }
    });

    app.run()
}
