// ---------- theme (DESIGN.md §5.1), as in omaphoenix-gui ----------

const TOKEN_MAP: &[(&str, &[&str])] = &[
    ("surface-base", &["background"]),
    ("surface-sunken", &["dark_background", "background"]),
    (
        "surface-deep",
        &["darker_background", "dark_background", "background"],
    ),
    (
        "surface-raised",
        &["lighter_background", "selection", "background"],
    ),
    ("text-primary", &["foreground"]),
    ("text-secondary", &["light_foreground", "foreground"]),
    ("text-muted", &["muted", "dark_foreground", "foreground"]),
    ("accent", &["accent", "blue"]),
    ("selection", &["selection", "lighter_background"]),
    ("state-risk", &["red"]),
    ("state-attention", &["yellow"]),
    ("state-fine", &["green"]),
    ("state-info", &["cyan", "blue"]),
];

fn theme_file() -> Option<PathBuf> {
    let state = env::var_os("XDG_STATE_HOME")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .or_else(|| env::var_os("HOME").map(|h| Path::new(&h).join(".local/state")))?;
    Some(state.join("omarchy/current/theme/colors.toml"))
}

fn parse_hex(s: &str) -> Option<slint::Color> {
    let s = s.trim().strip_prefix('#')?;
    let byte = |i: usize| s.get(i..i + 2).and_then(|b| u8::from_str_radix(b, 16).ok());
    Some(slint::Color::from_rgb_u8(byte(0)?, byte(2)?, byte(4)?))
}

fn read_tokens(path: &Path) -> Option<BTreeMap<&'static str, slint::Color>> {
    let table: toml::Table = fs::read_to_string(path).ok()?.parse().ok()?;
    let hex = |k: &str| {
        table
            .get(k)
            .and_then(toml::Value::as_str)
            .and_then(parse_hex)
    };
    Some(
        TOKEN_MAP
            .iter()
            .filter_map(|(token, keys)| keys.iter().find_map(|k| hex(k)).map(|c| (*token, c)))
            .collect(),
    )
}

fn apply_theme(app: &App, tokens: &BTreeMap<&'static str, slint::Color>) {
    let t = app.global::<Theme>();
    for (k, c) in tokens {
        match *k {
            "surface-base" => t.set_surface_base(*c),
            "surface-sunken" => t.set_surface_sunken(*c),
            "surface-deep" => t.set_surface_deep(*c),
            "surface-raised" => t.set_surface_raised(*c),
            "text-primary" => t.set_text_primary(*c),
            "text-secondary" => t.set_text_secondary(*c),
            "text-muted" => t.set_text_muted(*c),
            "accent" => t.set_accent(*c),
            "selection" => t.set_selection(*c),
            "state-risk" => t.set_state_risk(*c),
            "state-attention" => t.set_state_attention(*c),
            "state-fine" => t.set_state_fine(*c),
            "state-info" => t.set_state_info(*c),
            _ => {}
        }
    }
}

/// Follows Omarchy theme switches (the `current/theme` symlink is swapped).
fn watch_theme(app: Weak<App>) {
    thread::spawn(move || {
        let stamp = |p: &Path| -> Option<(PathBuf, SystemTime)> {
            let real = fs::canonicalize(p).ok()?;
            Some((real.clone(), fs::metadata(&real).ok()?.modified().ok()?))
        };
        let Some(path) = theme_file() else { return };
        let mut last = stamp(&path);
        loop {
            thread::sleep(Duration::from_millis(400));
            let now = stamp(&path);
            if now == last {
                continue;
            }
            last = now;
            if let Some(tokens) = read_tokens(&path) {
                let app = app.clone();
                let _ = slint::invoke_from_event_loop(move || {
                    if let Some(app) = app.upgrade() {
                        apply_theme(&app, &tokens);
                    }
                });
            }
        }
    });
}

// ---------- state ----------

/// Tabs, as `in_tab()` in the terminal app.
fn in_tab(tab: i32, f: &Item) -> bool {
    let sev = sev_name(f.finding.sev);
    match tab {
        0 => f.is_issue() && !f.accepted,
        1 => f.accepted,
        2 => matches!(sev, "info" | "skip"),
        3 => sev == "pass",
        _ => true,
    }
}

struct State {
    store: Store,
    runs: Vec<Run>,
    current: usize,
    accepted: BTreeMap<String, Accepted>,
    /// Line numbers (`Item::n`) behind the rows on screen.
    shown: Vec<usize>,
    toast_until: Option<Instant>,
    /// History row armed for deletion, and until when.
    delete_armed: Option<(usize, Instant)>,
    /// The AI conversation on screen, if any.
    ai: Option<AiSess>,
    /// What the consent dialog leads to, and its backend choice.
    setup: Option<(Then, &'static str)>,
}

/// What asking Claude is about.
#[derive(Clone, Copy)]
enum Then {
    /// Finding `n` of the current run.
    Explain(usize),
    Plan,
}

/// One AI conversation (the original's `AIScreen` state).
struct AiSess {
    prompt: String,
    title: String,
    backend: &'static str,
    messages: Vec<Value>,
    session: Option<String>,
    request: Option<Request>,
    rx: Option<Receiver<Event>>,
    /// (is a question, text)
    parts: Vec<(bool, String)>,
    streaming: String,
    last_answer: String,
    status: String,
    error: bool,
    busy: bool,
}

impl State {
    fn run(&self) -> Option<&Run> {
        self.runs.get(self.current)
    }

    fn reload(&mut self) {
        self.accepted = self.store.accepted();
        self.runs = self.store.runs();
        for r in &mut self.runs {
            r.recount(&self.accepted);
        }
        self.current = self.current.min(self.runs.len().saturating_sub(1));
    }
}

type Shared = Rc<RefCell<State>>;

thread_local! {
    static STATE: RefCell<Option<Shared>> = const { RefCell::new(None) };
}

fn state() -> Shared {
    STATE.with(|s| s.borrow().clone()).unwrap_or_else(|| {
        Rc::new(RefCell::new(State {
            store: Store::from_env(),
            runs: Vec::new(),
            current: 0,
            accepted: BTreeMap::new(),
            shown: Vec::new(),
            toast_until: None,
            delete_armed: None,
            ai: None,
            setup: None,
        }))
    })
}

fn model<T: Clone + 'static>(v: Vec<T>) -> ModelRc<T> {
    ModelRc::new(Rc::new(VecModel::from(v)))
}

fn int(n: usize) -> i32 {
    i32::try_from(n).unwrap_or(i32::MAX)
}

/// `date -d @epoch +fmt`: local time without a time-zone crate.
fn local(epoch: u64, fmt: &str) -> String {
    Command::new("date")
        .args(["-d", &format!("@{epoch}"), &format!("+{fmt}")])
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_default()
}

fn toast(app: &App, msg: impl Into<SharedString>) {
    app.set_toast(msg.into());
    state().borrow_mut().toast_until = Some(Instant::now() + Duration::from_secs(5));
}

/// Puts the current run, tab and search on screen.
fn refresh(app: &App) {
    let shared = state();
    let mut s = shared.borrow_mut();
    let Some(run) = s.run() else {
        app.set_has_run(false);
        app.set_history(model(Vec::new()));
        return;
    };
    let c = run.counts();
    app.set_has_run(true);
    let latest = s.current == 0;
    app.set_when(
        format!(
            "{} · {} scan{}",
            local(run.meta.started, "%a %-d %b %H:%M"),
            run.meta.mode,
            if latest { "" } else { " (older scan)" }
        )
        .into(),
    );
    let score = c.score();
    app.set_score(i32::try_from(score).unwrap_or(0));
    app.set_grade(c.grade().to_string().into());
    #[allow(clippy::cast_precision_loss, reason = "a score of 0-100")]
    app.set_ring(score as f32);
    app.set_fails(int(c.fail));
    app.set_warns(int(c.warn));
    app.set_passes(int(c.pass));
    app.set_notes(int(c.info + c.skip));
    app.set_accepted(int(c.accepted));
    app.set_tabs(model(vec![
        format!("Issues {}", c.fail + c.warn).into(),
        format!("Accepted {}", c.accepted).into(),
        format!("Notes {}", c.info + c.skip).into(),
        format!("Passed {}", c.pass).into(),
        format!("All {}", run.items.len()).into(),
    ]));
    let since = match s.runs.get(s.current + 1) {
        Some(prev) => {
            let (a, b) = (run.issue_keys(), prev.issue_keys());
            format!(
                "Since the previous scan: {} new · {} resolved",
                a.difference(&b).count(),
                b.difference(&a).count()
            )
        }
        None => "First scan on record".into(),
    };
    app.set_since(since.into());

    let q = app.get_query().to_lowercase();
    let tab = app.get_tab();
    let applied = run.applied();
    let mut items: Vec<&Item> = run
        .items
        .iter()
        .filter(|f| in_tab(tab, f))
        .filter(|f| {
            let fd = &f.finding;
            q.is_empty()
                || format!(
                    "{}\n{}\n{}\n{}\n{}",
                    fd.msg, fd.section, fd.detail, fd.fix, fd.hint
                )
                .to_lowercase()
                .contains(&q)
        })
        .collect();
    items.sort_by_key(|f| (sev_order(f.finding.sev), f.n));
    let rows: Vec<Row> = items
        .iter()
        .map(|f| Row {
            sev: sev_name(f.finding.sev).into(),
            title: f.title().into(),
            section: f.finding.section.as_str().into(),
            detail: f.finding.detail.as_str().into(),
            fix: f.finding.fix.as_str().into(),
            hint: f.finding.hint.as_str().into(),
            accepted: f.accepted,
            applied: applied.contains(&f.n),
        })
        .collect();
    s.shown = items.iter().map(|f| f.n).collect();
    let n = rows.len();
    app.set_rows(model(rows));
    app.set_sel(app.get_sel().min(int(n.saturating_sub(1))).max(0));

    set_history(app, &s);
}

/// The history sheet: every scan, newest first, compared with the one before.
fn set_history(app: &App, state: &State) {
    let history: Vec<Past> = state
        .runs
        .iter()
        .enumerate()
        .map(|(i, r)| {
            let c = r.counts();
            let change = match state.runs.get(i + 1) {
                Some(p) => {
                    let (a, b) = (r.issue_keys(), p.issue_keys());
                    format!(
                        "+{} new  −{} resolved",
                        a.difference(&b).count(),
                        b.difference(&a).count()
                    )
                }
                None => "first scan".into(),
            };
            Past {
                label: local(r.meta.started, "%a %-d %b %H:%M").into(),
                score: i32::try_from(c.score()).unwrap_or(0),
                grade: c.grade().to_string().into(),
                mode: r.meta.mode.as_str().into(),
                change: change.into(),
            }
        })
        .collect();
    app.set_history(model(history));
}

/// The selected finding of the current run.
fn selected(app: &App) -> Option<(PathBuf, Item)> {
    let st = state();
    let s = st.borrow();
    let n = *s.shown.get(usize::try_from(app.get_sel()).ok()?)?;
    let run = s.run()?;
    Some((
        run.path.clone(),
        run.items.iter().find(|i| i.n == n)?.clone(),
    ))
}

